export function buildingForZone(zone: ZoneType, stage: number): BuildingKind {
  const dense = isDenseZone(zone);
  if (zone === 'r_light' || zone === 'r_dense') {
    if (stage <= 0) return 'none';
    return dense && stage >= 3 ? 'apartment' : 'house';
  }
  if (zone === 'c_light' || zone === 'c_dense') {
    if (stage <= 0) return 'none';
    return dense && stage >= 3 ? 'office' : 'shop';
  }
  if (zone === 'i_light' || zone === 'i_dense') {
    if (stage <= 0) return 'none';
    return dense && stage >= 3 ? 'factory' : 'warehouse';
  }
  return 'none';
}

export function populationForTile(
  building: BuildingKind,
  stage: number,
): { residents: number; jobs: number } {
  const def = BUILDINGS[building];
  if (building === 'none' || building === 'abandoned' || stage <= 0) {
    return { residents: 0, jobs: 0 };
  }
  const scale = Math.min(1, 0.35 + stage * 0.2);
  return {
    residents: Math.round(def.residents * scale),
    jobs: Math.round(def.jobs * scale),
  };
}
